public class Temp {

    private String target;
    private int x;

    public Temp(String target){
        this.target = target;
    }

    public Temp(int x){
        this.x = x;
    }

    public Temp(){};

    public String getTarget() {
        return target;
    }

    public int getX() {
        return x;
    }
}
